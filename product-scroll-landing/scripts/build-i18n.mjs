// i18n/{ru,en,he,ar}.txt ("key = text" per line) -> lib/dict.ts
// Russian is the source; en/he/ar come from the Translater worker (C:\agents\Translater), never translated by hand.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LANGS = ['en', 'ru', 'he', 'ar'];

const parse = (lang) => {
  const out = {};
  const file = join(root, 'i18n', `${lang}.txt`);
  if (!existsSync(file)) return out;
  const txt = readFileSync(file, 'utf8').replace(/^\uFEFF/, '');
  for (const raw of txt.split(/\r?\n/)) {
    const m = raw.match(/^\s*[\u200E\u200F]?\s*([a-z][a-z0-9_]*)\s*=\s*(.*)$/i);
    if (m) out[m[1]] = m[2].trim();
  }
  return out;
};

const dicts = Object.fromEntries(LANGS.map((l) => [l, parse(l)]));
const keys = Object.keys(dicts.ru);
let problems = 0;
for (const l of LANGS) {
  const miss = keys.filter((k) => !dicts[l][k]);
  if (miss.length) { problems++; console.warn(`[${l}] missing ${miss.length}: ${miss.join(', ')}`); }
}

const body = LANGS.map((l) => `  ${l}: ${JSON.stringify(dicts[l], null, 4).replace(/\n}/, '\n  }')},`).join('\n');
writeFileSync(join(root, 'lib', 'dict.ts'),
  `// Generated by scripts/build-i18n.mjs from i18n/*.txt. Do not edit by hand: edit i18n/ru.txt, translate with Translater, run \`npm run i18n\`.\n` +
  `export const DICTS = {\n${body}\n} as const satisfies Record<string, Record<string, string>>;\n`);
console.log(`lib/dict.ts: ${keys.length} keys × ${LANGS.length} languages${problems ? ' (with gaps, English is the fallback)' : ''}`);
